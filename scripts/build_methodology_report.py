         "controlled vocabulary shared by the offline pipeline and the live re-scoring path "
         "(ml-service/data_pipeline/status_vocabulary.py). An ordered rule cascade with explicit "
         "negative guards resolves 96.9% of monitoring rows and abstains on the rest rather than "
         "guessing, recording provenance in a status_source column exactly as D12's "
         f"project_type_source does ({f['status_source_train']} across the training split). The "
