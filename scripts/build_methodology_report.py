def load_json(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def gather(pre_artifacts: Path | None) -> dict:
    trees = load_json(ARTIFACTS / "tree_models_metrics.json")
    lstm = load_json(ARTIFACTS / "lstm_model_metrics.json")
    meta = load_json(ARTIFACTS / "meta_learner_metrics.json")
    cols = load_json(ARTIFACTS / "tabular_feature_columns.json") or []

    train = pd.read_csv(READY / "train.csv", low_memory=False)
    test = pd.read_csv(READY / "test.csv", low_memory=False)
    inference = pd.read_csv(READY / "inference.csv", low_memory=False)

    def family(prefix: str) -> list[str]:
        return sorted(c[len(prefix):] for c in cols if c.startswith(prefix))

    status = family("STATUS_canonical_")
    municipality = family("municipality_canonical_")
    project_type = family("project_type_")
    contractor_spec = family("contractor_spec_")
    onehot_total = len(status) + len(municipality) + len(project_type) + len(contractor_spec)

    facts = {
        "trees": trees,
        "lstm": lstm,
        "meta": meta,
        "n_features": len(cols),
        "status_members": status,
        "municipality_members": municipality,
        "project_type_members": project_type,
        "contractor_spec_members": contractor_spec,
        "n_onehot": onehot_total,
        "n_continuous": len(cols) - onehot_total,
        "continuous_members": sorted(
            c for c in cols
            if not any(c.startswith(p) for p in
                       ("STATUS_canonical_", "municipality_canonical_",
                        "project_type_", "contractor_spec_"))
        ),
        "n_train": len(train),
        "n_test": len(test),
        "n_inference": len(inference),
        "n_labeled": len(train) + len(test),
        "redflag_train": int(train["RedFlag"].sum()),
        "redflag_test": int(test["RedFlag"].sum()),
        "clamped_train": int(train.get("completion_date_is_clamped", pd.Series(dtype=bool)).sum()),
        "clamped_test": int(test.get("completion_date_is_clamped", pd.Series(dtype=bool)).sum()),
        "flags": {
            f: (int(train[f].sum()), int(test[f].sum()))
            for f in ("status_has_damage", "status_not_turned_over", "status_partially_functional")
            if f in train.columns
        },
        "status_source_train": (
            train["status_source"].value_counts().to_dict()
            if "status_source" in train.columns else {}
        ),
        "pre": None,
    }
    facts["n_total_rows"] = facts["n_labeled"] + facts["n_inference"]

    if pre_artifacts and pre_artifacts.exists():
        facts["pre"] = {
            "trees": load_json(pre_artifacts / "tree_models_metrics.json"),
            "lstm": load_json(pre_artifacts / "lstm_model_metrics.json"),
            "meta": load_json(pre_artifacts / "meta_learner_metrics.json"),
            "cols": load_json(pre_artifacts / "tabular_feature_columns.json") or [],
        }
    return facts


# ---------------------------------------------------------------------------
# Document helpers
